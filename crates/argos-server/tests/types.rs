use argos_server::types::*;
use ts_rs::TS;
#[test]
fn generated_types_match_rust_contracts() {
    let config = ts_rs::Config::default();
    let mut text =
        String::from("// Generated by cargo test -p argos-server --test types. Do not edit.\n");
    macro_rules! add {($($t:ty),*)=>{$(text.push_str("export ");text.push_str(&<$t>::decl(&config));text.push('\n');)*}}
    add!(
        NavigationParameters,
        NavigationState,
        NavigationRequest,
        Occupancy,
        Identity,
        Pose,
        Authority,
        Hardware,
        Reference,
        Goal,
        Rover,
        Waypoint,
        WaypointRequest,
        CancelRequest,
        HardwareRequest,
        AutonomyRequest,
        DriveRequest,
        Operation,
        Claim,
        FleetSnapshot,
        PublicConfig
    );
    let path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../apps/web/src/generated.ts");
    if std::env::var("ARGOS_CHECK_TYPES").is_ok() {
        assert_eq!(
            std::fs::read_to_string(path).unwrap().replace("\r\n", "\n"),
            text,
            "Regenerate and commit API types"
        );
    } else {
        std::fs::write(path, text).unwrap();
    }
}
